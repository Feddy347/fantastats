// One-off generator: reads data/fantastats_giocatori_2627.csv (the 2026/27
// listone) and writes supabase/seed.sql — a full reload of teams + players.
//
// DELETE on public.players cascades to every table with a player_id FK
// (on delete cascade): user_players, player_prices, league_rosters,
// league_lineup_players, auction_log, sealed_bids, lineup_players,
// player_match_stats, player_match_scores, sorare_player_mapping.
// public.teams has no incoming FK (players.team is a plain text column,
// matched by name), so it can be reloaded independently.
//
// birth_year/nationality are intentionally left out of this insert —
// scripts/enrich-players.js populates them (and sorare_player_mapping.slug)
// afterwards via Sorare's searchPlayers query.
//
// Usage: node scripts/generate-seed-sql.js

import fs from 'node:fs'

const CSV_PATH = 'data/fantastats_giocatori_2627.csv'
const OUT_PATH = 'supabase/seed.sql'

function parseCsv(raw) {
  const lines = raw.split(/\r\n|\n/).filter((l) => l.length > 0)
  const header = lines[0].split(',')
  const rows = lines.slice(1).map((line) => {
    const cols = line.split(',')
    const obj = {}
    header.forEach((h, i) => (obj[h] = cols[i]))
    return obj
  })
  return rows
}

function sqlString(value) {
  return `'${String(value).replace(/'/g, "''")}'`
}

function main() {
  const raw = fs.readFileSync(CSV_PATH, 'utf8')
  const rows = parseCsv(raw)

  const teams = [...new Set(rows.map((r) => r.Squadra))].sort()

  const teamValues = teams.map((t) => `  (${sqlString(t)})`).join(',\n')

  const playerValues = rows
    .map((r) => {
      const id = Number(r.Id)
      const name = sqlString(r.Nome)
      const team = sqlString(r.Squadra)
      const roleClassic = sqlString(r.Ruolo_Classic)
      const roleMantra = sqlString(r.Ruolo_Mantra)
      const roleFantastats = sqlString(r.Ruolo_Fantastats)
      const priceCurrent = Number(r.Quot_Attuale)
      const priceInitial = Number(r.Quot_Iniziale)
      const fantaValue = Number(r.FantaValore)
      return `  (${id}, ${name}, ${team}, ${roleClassic}, ${roleMantra}, ${roleFantastats}, ${priceCurrent}, ${priceInitial}, ${fantaValue})`
    })
    .join(',\n')

  const sql = `-- Fantastats: full reload of players/teams from the 2026/27 listone
-- (data/fantastats_giocatori_2627.csv, ${rows.length} players / ${teams.length} teams).
-- Generated by scripts/generate-seed-sql.js — do not hand-edit, regenerate instead.
--
-- DELETE on players cascades to every table with a player_id FK (on delete
-- cascade): user_players, player_prices, league_rosters,
-- league_lineup_players, auction_log, sealed_bids, lineup_players,
-- player_match_stats, player_match_scores, sorare_player_mapping.
-- teams has no incoming FK (players.team is text, matched by name), so it
-- reloads independently of the cascade.
--
-- birth_year/nationality are left null here on purpose — run
-- scripts/enrich-players.js afterwards to populate them (and the Sorare
-- slug mapping in sorare_player_mapping) via searchPlayers.

delete from public.players;
delete from public.teams;

insert into public.teams (name) values
${teamValues};

insert into public.players (id, name, team, role_classic, role_mantra, role_fantastats, price_current, price_initial, fanta_value) values
${playerValues};
`

  fs.writeFileSync(OUT_PATH, sql)
  console.log(`Wrote ${OUT_PATH}: ${teams.length} teams, ${rows.length} players.`)
}

main()
